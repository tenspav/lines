/* ---- emulator core stubs ---- */
u32 gba_icount;
static const u8 *(*s_fault)(GBA *, u32);
static uint32_t s_frames;
void gba_set_rom(GBA *gg, u32 size, const u8 *(*fault)(GBA *, u32), void *user) { (void)user; gg->rom_size = size; s_fault = fault; }
void gba_reset(GBA *gg) { gg->r[15] = 0x08000000u; }
void gba_set_save(GBA *gg, int type) { gg->save_type = type; for (u32 i = 0; i < sizeof gg->sram; i++) gg->sram[i] = 0xFF; }
static u8 rom_tag(u32 size) { return (u8)(size % 251u + 1u); }
void gba_run_frame(GBA *gg)
{
    s_frames++;
    gg->r[0]++;                                          /* "game progress" (state save/restore check) */
    {
    u32 pages = (gg->rom_size + ROM_PAGE_SIZE - 1) / ROM_PAGE_SIZE, lim = pages < 40 ? pages : 40;
    u32 page = lim ? (s_frames * 7u) % lim : 0;         /* touch ROM pages: slot cache + eviction */
    if (!gg->rom_tab[page]) s_fault(gg, page);
    gg->rom_ref[page] = 1;
    }
    if (s_frames % 60 == 0) {                            /* "the game writes its save": a per-ROM tag + a counter */
        gg->sram[0x200] = rom_tag(gg->rom_size);
        gg->sram[0x201]++;
        gg->flash_dirty = 1;
    }
}
u32 mem_read32(GBA *gg, u32 a) { (void)gg; (void)a; return 0; }
u32 gba_hle_status(GBA *gg) { (void)gg; return 0; }

