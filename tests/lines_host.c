/* lines_host.c - PC test of the Lines front end: ROM menu, per-ROM saves and states, ROM page cache, memory
 * release cycle (not part of the device build). Runs the real src/lines.c with the emulator core stubbed
 * (gba_run_frame touches a few ROM pages, bumps a "game progress" counter in r[0] and writes a per-ROM tag into
 * the save RAM) against a counting first-fit heap, a virtual clock and a directory/file layer rooted at ROOT.
 *   gcc -O1 -g -DLINES_HOST -DIDLE_FREE_US=20000000u -I../src -I/path/to/sdk -o lines_host lines_host.c
 *   ./lines_host ROOT SHOTDIR       (ROOT prepared by run_ui_tests.sh from synthetic ROMs generated by the test)
 * Checks (see main): ROM scan/sort/flags, menu tap + drag-scroll, per-ROM saves/states, an existing save.sav is
 * kept, ROMS hold -> menu (heap back to 0), EXIT / idle release + resume, last-ROM persistence, relaunch /
 * reinstall cases, single ROM / no ROM / vanished ROM.
 * Heap model: LINES_HEAP_FREE / LINES_HEAP_LARGEST bytes; LINES_POW2=1 rounds every request up to a power of two
 * like the OS allocator is said to; the resident is modelled (frees the aux block before every launch). */
