/* ---- heap: first fit below 4 GB, sized from the environment ---- */
static uint32_t HSZ = 8650000u;                       /* arena = free + pin */
static uint32_t HEAP_FREE = 8650000u - 16u, HEAP_LARGEST = 8388608u;
static int POW2;
typedef struct { uint32_t off, len, used; } blk_t;
static uint8_t *hbase; static blk_t hb[512]; static int nhb, n_alloc, n_bad; static uint32_t used, peak_used;
static uint32_t max_blk_bytes;
uint32_t hb_os_heap_free(void) { return HSZ - used - 16u; }
uint32_t hb_os_heap_largest(void) { uint32_t m = 0; for (int i = 0; i < nhb; i++) if (!hb[i].used && hb[i].len > m) m = hb[i].len; return m; }
static uint32_t p2(uint32_t n) { uint32_t r = 16; while (r < n) r <<= 1; return r; }
void *hb_os_alloc(uint32_t n)
{
    n = POW2 ? p2(n) : ((n + 15u) & ~15u);
    for (int i = 0; i < nhb; i++) {
        if (hb[i].used || hb[i].len < n) continue;
        if (hb[i].len > n) { memmove(&hb[i + 2], &hb[i + 1], (size_t)(nhb - i - 1) * sizeof hb[0]); hb[i + 1].off = hb[i].off + n; hb[i + 1].len = hb[i].len - n; hb[i + 1].used = 0; hb[i].len = n; nhb++; }
        hb[i].used = 1; used += hb[i].len; n_alloc++;
        if (used > peak_used) peak_used = used;
        if (hb[i].len > max_blk_bytes) max_blk_bytes = hb[i].len;
        memset(hbase + hb[i].off, 0xA5, hb[i].len);   /* OS heap is not zeroed */
        return hbase + hb[i].off;
    }
    return 0;
}
void hb_os_free(void *p)
{
    uint32_t off = (uint32_t)((uint8_t *)p - hbase); int i;
    for (i = 0; i < nhb; i++) if (hb[i].off == off && hb[i].used) break;
    if (i == nhb) { printf("HEAP ERROR: bad free %p\n", p); n_bad++; return; }
    memset(p, 0xEE, hb[i].len > 64 ? 64 : hb[i].len);
    hb[i].used = 0; used -= hb[i].len; n_alloc--;
    if (i + 1 < nhb && !hb[i + 1].used) { hb[i].len += hb[i + 1].len; memmove(&hb[i + 1], &hb[i + 2], (size_t)(nhb - i - 2) * sizeof hb[0]); nhb--; }
    if (i > 0 && !hb[i - 1].used) { hb[i - 1].len += hb[i].len; memmove(&hb[i], &hb[i + 1], (size_t)(nhb - i - 1) * sizeof hb[0]); nhb--; }
}
/* what the resident does before payload_entry on every launch: free the previous aux block */
static void resident_free_aux(void)
{
    void *a = HB_APP_AUX_BLOCK;
    if (a) { hb_os_free(a); HB_APP_AUX_BLOCK = 0; }
}
static void heap_init(void)
{
    /* [free: FREE-LARGEST][pin 16 B used][free: LARGEST]  -> free total FREE, largest LARGEST */
    uint32_t hole = HEAP_FREE - HEAP_LARGEST;
    HSZ = HEAP_FREE + 16u;
    hbase = mmap(0, HSZ + 4096, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_32BIT, -1, 0);
    nhb = 0;
    if (hole) { hb[nhb].off = 0; hb[nhb].len = hole; hb[nhb].used = 0; nhb++; }
    hb[nhb].off = hole; hb[nhb].len = 16; hb[nhb].used = 1; nhb++;
    hb[nhb].off = hole + 16; hb[nhb].len = HEAP_LARGEST; hb[nhb].used = 0; nhb++;
    used = 16; n_alloc = 0;
}

