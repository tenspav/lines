/* ---- files / directories ---- */
uint32_t hb_fs_read(const char *p, void *buf, uint32_t max)
{
    const char *b = strrchr(p, '/');
    FILE *f = fopen(hp(p), "rb");
    if (b && b[1] == 'p' && b[2] >= '0' && b[2] <= '9') { pg_reads++; }
    if (!f) return 0;
    size_t n = fread(buf, 1, max, f); fclose(f);
    if (b && b[1] == 'p' && b[2] >= '0' && b[2] <= '9') pg_bytes += n;
    return (uint32_t)n;
}
bool hb_fs_write(const char *p, const void *d, uint32_t n)
{
    FILE *f = fopen(hp(p), "wb"); if (!f) return false;
    size_t w = fwrite(d, 1, n, f); fclose(f); return w == n;
}
bool hb_fs_write_parts(const char *p, void *const *ptrs, const uint32_t *lens, int np)
{
    FILE *f = fopen(hp(p), "wb"); if (!f) return false;
    for (int i = 0; i < np; i++) fwrite(ptrs[i], 1, lens[i], f);
    fclose(f); return true;
}
bool hb_fs_exists(const char *p) { struct stat st; return stat(hp(p), &st) == 0; }
uint32_t hb_fs_size(const char *p) { struct stat st; return stat(hp(p), &st) ? 0 : (uint32_t)st.st_size; }
bool hb_fs_dir_open(hb_dir_t *it, const char *path, bool rec)
{
    (void)rec; DIR *d = opendir(hp(path)); memcpy(it->opaque, &d, sizeof d); return d != NULL;
}
bool hb_fs_dir_next(hb_dir_t *it, char *out, int sz, bool *isdir)
{
    DIR *d; struct dirent *e; memcpy(&d, it->opaque, sizeof d);
    while (d && (e = readdir(d))) {
        if (!strcmp(e->d_name, ".") || !strcmp(e->d_name, "..")) continue;
        snprintf(out, (size_t)sz, "%s", e->d_name);
        if (isdir) *isdir = e->d_type == DT_DIR;
        return true;
    }
    return false;
}
void hb_fs_dir_close(hb_dir_t *it) { DIR *d; memcpy(&d, it->opaque, sizeof d); if (d) closedir(d); }

