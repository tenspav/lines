static int fails;
static void check(const char *what, int ok) { printf("CHECK %-52s %s (heap used %u in %d blocks, free %u)\n", what, ok ? "OK" : "FAIL", used, n_alloc, hb_os_heap_free()); if (!ok) fails++; }
static int run_until(int st, int max) { while (max-- && state != st) frame(); return state == st; }
static int row_y(int idx) { return MN_TOP + idx * MN_ROW - mn_scroll + 12; }
static void drag_list(int dir)                           /* dir -1: finger up (list scrolls down) */
{
    touch(1, 100, 150); frames(2);
    for (int k = 1; k <= 6; k++) { touch(1, 100, 150 + dir * 20 * k); frames(1); }
    touch(0, 0, 0); frames(4);
}
static void tap_row(int idx)                             /* scrolls it into view first (landscape shows 3 rows) */
{
    for (int guard = 0; guard < 30 && idx >= 0 && (row_y(idx) < MN_TOP + 4 || row_y(idx) > LH - MN_BOT - 8); guard++)
        drag_list(row_y(idx) > LH - MN_BOT - 8 ? -1 : 1);
    tap_logical(100, row_y(idx));
}
static int idx_of(const char *d) { for (int i = 0; i < nroms; i++) if (!strcmp(roms[i].dir, d)) return i; return -1; }
static uint32_t u32_at(const char *path, uint32_t off) { uint8_t b[4] = { 0 }; FILE *f = fopen(hp(path), "rb"); if (!f) return 0xDEADBEEF; fseek(f, off, SEEK_SET); if (fread(b, 1, 4, f) != 4) { fclose(f); return 0xDEADBEEF; } fclose(f); return b[0] | (b[1] << 8) | (b[2] << 16) | ((uint32_t)b[3] << 24); }
static uint32_t hash_file(const char *path) { uint32_t h = 2166136261u; FILE *f = fopen(hp(path), "rb"); if (!f) return 0; int c; while ((c = fgetc(f)) != EOF) h = (h ^ (uint32_t)c) * 16777619u; fclose(f); return h; }
static int last_txt_is(const char *want) { char b[64] = { 0 }; hb_fs_read(GBA_ROOT "/last.txt", b, 40); return !strcmp(b, want); }
static uint8_t byte_at(const char *path, uint32_t off) { uint8_t b = 0xEE; FILE *f = fopen(hp(path), "rb"); if (!f) return b; fseek(f, off, SEEK_SET); if (fread(&b, 1, 1, f) != 1) b = 0xEE; fclose(f); return b; }
static void mv(const char *a, const char *b) { char x[1100], y[1100]; snprintf(x, sizeof x, "%s", hp(a)); snprintf(y, sizeof y, "%s", hp(b)); rename(x, y); }

#define FR  "/Apps/Data/GBA/big_rom"
#define FT  "/Apps/Data/GBA/flash_test"
#define HW  "/Apps/Data/GBA/hello_world"

int main(int argc, char **argv)
{
    if (argc < 3) return 2;
    snprintf(ROOT, sizeof ROOT, "%s", argv[1]);
    snprintf(SHOTS, sizeof SHOTS, "%s", argv[2]);
    if (getenv("LINES_HEAP_FREE")) HEAP_FREE = (uint32_t)atoll(getenv("LINES_HEAP_FREE"));
    if (getenv("LINES_HEAP_LARGEST")) HEAP_LARGEST = (uint32_t)atoll(getenv("LINES_HEAP_LARGEST"));
    if (HEAP_LARGEST > HEAP_FREE) HEAP_LARGEST = HEAP_FREE;
    POW2 = getenv("LINES_POW2") != 0;
    heap_init();
    printf("heap model: free %u largest %u pow2 %d\n", HEAP_FREE, HEAP_LARGEST, POW2);
    printf("sizeof(GBA) %zu\n", sizeof(GBA));

    /* a pre-existing save.sav of the big ROM (written by the test setup) must survive */
    uint32_t old_save_hash = hash_file(FR "/save.sav");
    check("pre-existing save.sav present", old_save_hash != 0);

    /* ---- 1. fresh launch, 5 ROM folders -> menu ---- */
    quiet = 0;
    launch();
    keep.k_landscape = 0;
    check("fresh launch (>=2 ROMs) -> menu", run_until(S_MENU, 20));
    check("scan: 5 valid ROMs (junk dirs ignored)", nroms == 5);
    {
        static const char *want[5] = { "big_rom", "flash_test", "hello_world", "huge_rom", "sram_test" };
        int ok = nroms == 5;
        for (int i = 0; ok && i < 5; i++) ok = !strcmp(roms[i].dir, want[i]);
        check("scan: sorted by folder name", ok);
    }
    check("scan: big_rom 4 MiB flash128 has save", roms[0].size == 0x400000u && roms[0].stype == SAVE_FLASH128 && roms[0].has_save);
    check("scan: flash_test has no save yet", !roms[idx_of("flash_test")].has_save && roms[idx_of("flash_test")].stype == SAVE_FLASH64);
    check("scan: 33 MB ROM flagged bad", roms[idx_of("huge_rom")].bad == 1 && !roms[idx_of("big_rom")].bad);
    check("no last.txt -> nothing highlighted", cur_idx == -1);
    frames(3); snap("menu_portrait");
    tap_row(idx_of("huge_rom"));
    check("tap on >32 MB ROM does not start it", state == S_MENU);
    tap_logical(100, 5);                                  /* header: not a row */
    check("tap on header does not start", state == S_MENU);

    /* ---- 2. pick flash_test, play, ROMS hold -> menu ---- */
    tap_row(idx_of("flash_test"));
    check("tap row -> loading flash_test", state != S_MENU);
    check("flash_test boots", run_until(S_RUN, 100));
    check("keep.k_rom == flash_test", !strcmp(keep.k_rom, "flash_test"));
    check("last.txt == flash_test", last_txt_is("flash_test"));
    check("fresh ROM: no state loaded (r0==0)", g->r[0] == 0);
    uint32_t loaded = used; int loaded_n = n_alloc;
    frames(400);                                          /* 6.6 s: game writes save at 1 s multiples, flush 2.5 s later */
    check("flash_test save.sav written with its tag", byte_at(FT "/save.sav", 0x200) == rom_tag(roms[idx_of("flash_test")].size));
    snap("game_portrait");
    uint32_t ft_r0_live = g->r[0];
    keep.k_landscape = 0;
    hold_roms();
    check("ROMS hold (portrait) -> menu", state == S_MENU);
    check("ROMS: heap back to 0 (all blocks freed)", APPU == 0 && n_alloc == 0);
    uint32_t ft_r0 = u32_at(FT "/state.bin", 16);
    check("ROMS: flash_test state.bin saved (r0 >= live)", ft_r0 != 0xDEADBEEF && ft_r0 >= ft_r0_live && ft_r0 < ft_r0_live + 80);
    frames(30);
    check("finger still down on ROMS: no ROM started", state == S_MENU);
    release();
    check("after lifting: still in menu (wait-for-up)", state == S_MENU && APPU == 0);
    check("flash_test highlighted as last", cur_idx == idx_of("flash_test"));
    snap("menu_portrait_last");

    /* ---- 3. a ROM with a pre-existing save.sav ---- */
    tap_row(idx_of("big_rom"));
    check("big_rom boots", run_until(S_RUN, 100));
    check("pre-existing save.sav untouched at boot", hash_file(FR "/save.sav") == old_save_hash);
    check("last.txt == big_rom", last_txt_is("big_rom"));
    check("cache sized by ROM: big_rom block larger than flash_test's, still ONE block", used > loaded && n_alloc == loaded_n && n_alloc == 1);
    check("block registered as the resident's aux block", HB_APP_AUX_BLOCK == (void *)((u8 *)g - BLK_HDR));
    uint32_t loaded_fr = used; int fr_slots = nslots;
    printf("  big_rom: block %u B, %d cache slots, heap free after %u B\n", keep.k_blk_bytes, nslots, hb_os_heap_free());
    frames(400);
    check("big_rom save: old content kept (0..0x1FF)", byte_at(FR "/save.sav", 0x10) == (uint8_t)(0x10 * 7) && byte_at(FR "/save.sav", 0x1FF) == (uint8_t)(0x1FF * 7));
    check("big_rom save: tail kept (0x400..)", byte_at(FR "/save.sav", 0x400) == (uint8_t)(0x400 * 7) && byte_at(FR "/save.sav", 0x1FFFF) == (uint8_t)(0x1FFFF * 7));
    check("big_rom save has ITS tag, flash_test's differs", byte_at(FR "/save.sav", 0x200) == rom_tag(0x400000u) && rom_tag(0x400000u) != rom_tag(roms[idx_of("flash_test")].size));
    check("flash_test save.sav untouched by big_rom", byte_at(FT "/save.sav", 0x200) == rom_tag(roms[idx_of("flash_test")].size));
    check("flash_test save.sav has no big_rom pattern", byte_at(FT "/save.sav", 0x10) != (uint8_t)(0x10 * 7) || byte_at(FT "/save.sav", 0x11) != (uint8_t)(0x11 * 7));
    uint32_t fr_r0_live = g->r[0];

    /* ---- 4. EXIT -> freed, tap -> last ROM (not the menu) ---- */
    keep.k_landscape = 0;
    hold_sair();
    check("EXIT -> freed, heap 0", state == S_FREED && APPU == 0);
    check("EXIT: big_rom state.bin advanced", u32_at(FR "/state.bin", 16) >= fr_r0_live);
    tap_screen();
    check("tap after EXIT -> resumes big_rom (no menu)", run_until(S_RUN, 100) && !strcmp(keep.k_rom, "big_rom"));
    check("resume: r0 continues", g->r[0] >= fr_r0_live);

    /* ---- 5. landscape: ROMS -> menu, pick hello_world; switch back and forth, check independence ---- */
    keep.k_landscape = 1; layout_dirty = 1;
    frames(20);
    hold_roms();
    check("ROMS hold (landscape) -> menu", state == S_MENU && APPU == 0);
    uint32_t fr_save_hash = hash_file(FR "/save.sav");     /* final big_rom save (flushed by the release) */
    release();
    check("landscape: finger lifted, still menu", state == S_MENU);
    frames(3); snap("menu_landscape");
    check("landscape menu: last (big_rom) highlighted", cur_idx == idx_of("big_rom"));
    tap_row(idx_of("hello_world"));
    check("landscape: tap row -> hello_world boots", run_until(S_RUN, 100) && !strcmp(keep.k_rom, "hello_world"));
    check("hello_world: fresh state (r0==0)", g->r[0] == 0);
    check("last.txt == hello_world", last_txt_is("hello_world"));
    frames(300);
    snap("game_landscape");
    check("hello_world 4 KB ROM: pages loaded without faults", state == S_RUN);
    hold_roms(); release();
    check("hello_world -> menu", state == S_MENU && APPU == 0);
    tap_row(idx_of("flash_test"));
    check("back to flash_test: its own state (r0 == saved)", run_until(S_RUN, 100) && g->r[0] == ft_r0);
    check("flash_test save intact", byte_at(FT "/save.sav", 0x200) == rom_tag(roms[idx_of("flash_test")].size));
    check("big_rom save.sav unchanged while others ran", hash_file(FR "/save.sav") == fr_save_hash);

    /* ---- 6. leak check over repeated switching (6 ROM switches through the menu) ---- */
    {
        uint32_t fp[6] = { 0 }; int ok = 1;
        static const char *seq[6] = { "big_rom", "hello_world", "flash_test", "big_rom", "sram_test", "flash_test" };
        static const char *names[6] = { "big_rom", "hello_world", "flash_test", "big_rom", "sram_test", "flash_test" };
        uint32_t seen_fr = 0, seen_ft = 0;
        (void)fp; (void)names;
        for (int k = 0; k < 6; k++) {
            frames(20); hold_roms(); release();
            if (state != S_MENU || APPU != 0 || n_alloc != 0 || HB_APP_AUX_BLOCK != 0) { ok = 0; printf("  sw%d: menu state %d used %u aux %p\n", k, state, used, HB_APP_AUX_BLOCK); }
            tap_row(idx_of(seq[k]));
            if (!run_until(S_RUN, 100) || strcmp(keep.k_rom, seq[k])) { ok = 0; printf("  sw%d: boot state %d rom %s want %s\n", k, state, keep.k_rom, seq[k]); }
            if (n_alloc != 1 || HB_APP_AUX_BLOCK != (void *)((u8 *)g - BLK_HDR)) { ok = 0; printf("  sw%d: %d blocks\n", k, n_alloc); }
            if (!strcmp(seq[k], "big_rom")) { if (seen_fr && used != seen_fr) { ok = 0; printf("  sw%d: big_rom footprint changed %u -> %u\n", k, seen_fr, used); } seen_fr = used; }
            if (!strcmp(seq[k], "flash_test")) { if (seen_ft && used != seen_ft) { ok = 0; printf("  sw%d: flash_test footprint changed\n", k); } seen_ft = used; }
            printf("  sw%d %-12s block %u B  slots %d  heap free %u\n", k, seq[k], keep.k_blk_bytes, nslots, hb_os_heap_free());
        }
        check("6 switches: 1 block while running, 0 blocks in menu, same footprint per ROM", ok && n_bad == 0 && seen_fr == loaded_fr && seen_ft == loaded);
        frames(20); hold_roms(); release();
        check("after the 6 switches: heap fully back (0 app blocks)", state == S_MENU && APPU == 0 && n_alloc == 0 && hb_os_heap_free() == HEAP_FREE - 16u);
        tap_row(idx_of("flash_test")); run_until(S_RUN, 100);
    }

    /* ---- 7. Home exit / relaunch / reinstall (the resident frees the aux block before every launch) ---- */
    frames(30);
    check("running: one heap block, registered as the aux block", n_alloc == 1 && HB_APP_AUX_BLOCK == (void *)((u8 *)g - BLK_HDR));
    {
        uint32_t r0_live = g->r[0];
        launch();                                         /* left with Home, then reopened */
        check("Home + reopen: resident freed the block (heap clean at entry)", APPU == 0 && n_alloc == 0 && keep.k_g == 0 && nslots == 0);
        frames(3);
        check("Home + reopen -> reloads the same ROM (no menu), one block", run_until(S_RUN, 200) && !strcmp(keep.k_rom, "flash_test") && used == loaded && n_alloc == 1);
        check("... from its last save state (r0 between saved and live)", g->r[0] >= ft_r0 && g->r[0] <= r0_live);
    }
    hold_sair();
    check("EXIT before fresh-image relaunch", state == S_FREED && APPU == 0 && HB_APP_AUX_BLOCK == 0);
    fresh_image(); launch();
    check("fresh image after EXIT -> straight to last ROM", run_until(S_RUN, 100) && !strcmp(keep.k_rom, "flash_test"));
    frames(30);
    keep.k_landscape = 0;
    hold_roms(); release();
    check("ROMS before fresh-image relaunch", state == S_MENU && APPU == 0);
    fresh_image(); launch();
    check("fresh image after ROMS -> menu", run_until(S_MENU, 50) && APPU == 0);
    frames(2);
    check("... with the last ROM highlighted", cur_idx == idx_of("flash_test"));
    tap_row(idx_of("flash_test"));
    run_until(S_RUN, 100);
    frames(30);
    fresh_image(); launch();                              /* reinstall while playing: block freed by the resident, no keep.bin reclaim */
    check("reinstall while playing -> reloads the last ROM, no leak", run_until(S_RUN, 100) && n_alloc == 1 && used == loaded && n_bad == 0);
    hold_roms(); release();
    tap_row(idx_of("big_rom"));
    check("... and big_rom boots after it (same footprint)", run_until(S_RUN, 100) && used == loaded_fr && nslots == fr_slots);

    /* ---- 8. idle (20 s) in game and in the menu ---- */
    keep.k_landscape = 0;
    frames(60 * 21);
    check("game idle 10 min -> freed (reason 2)", state == S_FREED && rel_reason == 2 && APPU == 0 && !fr_menu);
    snap("freed_game");
    tap_screen();
    check("tap -> resumes the last ROM", run_until(S_RUN, 100) && !strcmp(keep.k_rom, "big_rom"));
    hold_roms(); release();
    check("menu again", state == S_MENU);
    frames(60 * 21);
    check("menu idle -> freed screen (nothing allocated)", state == S_FREED && fr_menu && APPU == 0);
    snap("freed_menu");
    tap_screen();
    check("tap after menu idle -> back to the menu", run_until(S_MENU, 50) && APPU == 0);
    frames(2);

    /* ---- 9. rotate in the menu ---- */
    {
        int was = keep.k_landscape;
        tap_logical(LW - 20, 15);
        check("ROT in the menu toggles the layout", keep.k_landscape == !was && state == S_MENU);
        tap_logical(LW - 20, 15);
        check("ROT again restores it", keep.k_landscape == was);
    }

    /* ---- 10. vanished ROM -> error -> menu ---- */
    mv(HW "/meta.bin", "/Apps/Data/GBA/hello_world_meta.bak");
    tap_row(idx_of("hello_world"));                        /* listed before the meta disappeared */
    run_until(S_ERROR, 50);
    check("ROM without meta.bin -> error screen", state == S_ERROR && err_code == 2);
    frames(3); snap("error");
    tap_screen();
    check("tap on the error -> menu (re-scanned, 4 ROMs)", run_until(S_MENU, 20) && nroms == 4 && idx_of("hello_world") < 0);
    check("error exit frees the half-loaded emulator block", APPU == 0 && n_alloc == 0 && n_bad == 0);
    mv("/Apps/Data/GBA/hello_world_meta.bak", HW "/meta.bin");

    /* ---- 11. long list: drag-scroll, tap after scrolling ---- */
    {
        char cmd[1200];
        for (int i = 0; i < 14; i++) {
            snprintf(cmd, sizeof cmd, "mkdir -p '%s/Apps/Data/GBA/extra_rom_%02d' && cp '%s/Apps/Data/GBA/hello_world/meta.bin' '%s/Apps/Data/GBA/hello_world/p000.bin' '%s/Apps/Data/GBA/extra_rom_%02d/'", ROOT, i, ROOT, ROOT, ROOT, i);
            if (system(cmd)) return 3;
        }
        keep.k_landscape = 0;
        hb_fs_write(GBA_ROOT "/last.txt", "sram_test", 9);        /* a late-sorting last ROM: the list opens scrolled */
        fresh_image(); launch();
        check("long list: 19 ROMs (14 extra) -> menu", run_until(S_MENU, 20) && nroms == 19);
        frames(3);
        int maxs = mn_max();
        check("long list scrollable; opens centred on the last ROM", maxs > 300 && mn_scroll == mn_clamp(cur_idx * MN_ROW - (mn_listh() - MN_ROW) / 2) && mn_scroll > 300);
        int s0 = mn_scroll;
        touch(1, 100, 100); frames(2);
        for (int y = 100; y <= 300; y += 20) { touch(1, 100, y); frames(1); }
        touch(0, 0, 0); frames(4);
        printf("  mn_scroll before %d after drag %d (cur_idx %d)\n", s0, mn_scroll, cur_idx);
        check("drag down 200 px moves the list by exactly 200", mn_scroll == s0 - 200 && state == S_MENU);
        frames(2); snap("menu_scrolled");
        int before = mn_scroll, want = (before + 200) / MN_ROW;
        check("target row is inside the list", row_y(want) > MN_TOP && row_y(want) < LH - MN_BOT);
        tap_row(want);
        check("tap after scrolling picks the right row", state != S_MENU && !strcmp(keep.k_rom, roms[want].dir));
        run_until(S_RUN, 100);
        hold_roms(); release();
        check("scroll position centres the last ROM", state == S_MENU && cur_idx == want && mn_scroll == mn_clamp(cur_idx * MN_ROW - (mn_listh() - MN_ROW) / 2));
        for (int i = 0; i < 14; i++) { snprintf(cmd, sizeof cmd, "rm -rf '%s/Apps/Data/GBA/extra_rom_%02d'", ROOT, i); if (system(cmd)) return 3; }
    }

    /* ---- 12. last ROM deleted; single ROM; no ROM ---- */
    hb_fs_write(GBA_ROOT "/last.txt", "gone_rom\n", 9);
    remove(hp(KEEP_PATH));                                /* no release marker */
    fresh_image(); launch();
    check("last ROM gone -> menu, nothing highlighted", run_until(S_MENU, 20) && cur_idx == -1);
    mv("/Apps/Data/GBA/flash_test", "/Apps/Data/hold_ft");
    mv("/Apps/Data/GBA/hello_world", "/Apps/Data/hold_hw");
    mv("/Apps/Data/GBA/huge_rom", "/Apps/Data/hold_hg");
    mv("/Apps/Data/GBA/sram_test", "/Apps/Data/hold_sr");
    remove(hp(KEEP_PATH));
    fresh_image(); launch();
    check("single ROM -> straight into it (no menu)", run_until(S_RUN, 100) && !strcmp(keep.k_rom, "big_rom") && nroms == 1);
    hold_roms(); release();
    check("single ROM: ROMS still opens the menu (1 row)", state == S_MENU && nroms == 1);
    mv("/Apps/Data/GBA/big_rom", "/Apps/Data/hold_fr");
    fresh_image(); launch();
    check("no ROM -> empty menu", run_until(S_MENU, 20) && nroms == 0);
    frames(3); snap("menu_empty");
    tap_row(0);
    check("empty menu: tap does nothing", state == S_MENU);
    mv("/Apps/Data/hold_fr", "/Apps/Data/GBA/big_rom");
    mv("/Apps/Data/hold_ft", "/Apps/Data/GBA/flash_test");
    mv("/Apps/Data/hold_hw", "/Apps/Data/GBA/hello_world");
    mv("/Apps/Data/hold_hg", "/Apps/Data/GBA/huge_rom");
    mv("/Apps/Data/hold_sr", "/Apps/Data/GBA/sram_test");

    printf("heap budget: peak app bytes %u (max single block %u), ROM page file reads %llu = %.1f MiB, est. disk %.1f s (14 MB/s + 256 us/open)\n",
           peak_used - 16u, max_blk_bytes, (unsigned long long)pg_reads, (double)pg_bytes / 1048576.0,
           (double)pg_reads * (DISK_OPEN_MS + DISK_MS_PER_PAGE) / 1000.0);
    printf("final heap: app blocks %d, free %u of %u\n", n_alloc, hb_os_heap_free(), HEAP_FREE);
    printf("bad frees %d, fails %d\n", n_bad, fails);
    return fails || n_bad;
}
